# Generate area codes for phone numbers
AREA_CODES = [str(x).zfill(3) for x in range(201, 999) if x not in [555, 666, 999]]

def generate_npi():
    """Generate a 10-digit NPI number with proper format."""
    prefix = random.choice(NPI_PREFIXES)
    suffix = ''.join(random.choices(string.digits, k=8))
    return prefix + suffix

def generate_phone():
    """Generate a properly formatted phone number."""
    area = random.choice(AREA_CODES)
    prefix = str(random.randint(200, 999))
    line = str(random.randint(1000, 9999))
    return f"{area}-{prefix}-{line}"

def generate_tax_id():
    """Generate a 9-digit tax ID."""
    return ''.join(random.choices(string.digits, k=9))

def generate_policy_number():
    """Generate an insurance policy number."""
    letters = ''.join(random.choices(string.ascii_uppercase, k=2))
    numbers = ''.join(random.choices(string.digits, k=6))
    return f"{letters}{numbers}"

def generate_account_number():
    """Generate a patient account number."""
    prefix = random.choice(["A", "P", "M"])
    numbers = ''.join(random.choices(string.digits, k=7))
    return f"{prefix}{numbers}"
